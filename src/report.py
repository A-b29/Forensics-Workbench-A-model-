"""
report.py - Report generation engine for Model Forensics Workbench.
"""

from pathlib import Path
from typing import Dict, Any, List
import json
import pandas as pd


def export_forensics_json(data: Dict[str, Any], output_path: Path) -> Path:
    """Save full forensics findings to JSON."""
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, default=str)
    return output_path


def generate_forensics_markdown(
    agg_metrics: Dict[str, Any],
    per_class_metrics: List[Dict[str, Any]],
    subgroup_results: Dict[str, List[Dict[str, Any]]],
    output_path: Path
) -> Path:
    """Generate Markdown report for model error forensics."""
    output_path.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        "# Model Failure Forensics Audit Report",
        "",
        "> **Methodological Disclaimer (Association vs. Causation):**",
        "> Identified subgroup disparities and proxy correlations are **exploratory hypotheses**. "
        "Statistical associations between sample metadata and misclassifications do not prove causal mechanisms "
        "and must be validated on independent prospective cohorts.",
        "",
        "## 1. Aggregate Performance",
        f"- **Total Samples:** `{agg_metrics.get('total_samples', 0)}`",
        f"- **Overall Error Rate:** `{agg_metrics.get('overall_error_rate', 0.0):.2%}` (Accuracy: `{agg_metrics.get('overall_accuracy', 0.0):.2%}`)",
        f"- **Balanced Accuracy:** `{agg_metrics.get('balanced_accuracy', 0.0):.2%}`",
        f"- **Macro F1 Score:** `{agg_metrics.get('macro_f1', 0.0):.4f}`",
    ]

    if "ece" in agg_metrics and agg_metrics["ece"] is not None:
        lines.append(f"- **Expected Calibration Error (ECE):** `{agg_metrics['ece']:.4f}`")
    if "high_confidence_errors" in agg_metrics:
        lines.append(f"- **High-Confidence Errors (Conf > 0.80):** `{agg_metrics['high_confidence_errors']}`")

    lines.extend([
        "",
        "## 2. Per-Class Error Breakdown",
        "",
        "| Class | Support | Sensitivity / Recall | Precision | Specificity | False Negatives | Error Rate |",
        "| :--- | :---: | :---: | :---: | :---: | :---: | :---: |",
    ])

    for row in per_class_metrics:
        lines.append(
            f"| {row['class_name']} | {row['support']} | {row['recall_sensitivity']:.2%} | "
            f"{row['precision']:.2%} | {row['specificity']:.2%} | {row['false_negatives']} | {row['class_error_rate']:.2%} |"
        )

    lines.extend([
        "",
        "## 3. Disaggregated Subgroup Forensics",
        "Subgroups ranked by error rate. Bounded with **95% Wilson Score Confidence Intervals** to detect small-sample volatility.",
        ""
    ])

    for col_name, groups in subgroup_results.items():
        lines.append(f"### Subgroup Dimension: `{col_name}`")
        lines.append("")
        lines.append("| Cohort Value | Sample Count | Errors | Error Rate | 95% Wilson CI | Risk Ratio | Statistical Flag |")
        lines.append("| :--- | :---: | :---: | :---: | :---: | :---: | :---: |")

        for g in groups:
            flag = "⚠️ Small Sample (< Min Size)" if g["is_unstable_small_cohort"] else "Valid Cohort"
            ci_str = f"[{g['ci_95_lower']:.1%}, {g['ci_95_upper']:.1%}]"
            lines.append(
                f"| `{g['subgroup_value']}` | {g['sample_count']} | {g['error_count']} | "
                f"**{g['error_rate']:.1%}** | {ci_str} | {g['risk_ratio']:.2f}x | {flag} |"
            )
        lines.append("")

    lines.extend([
        "## 4. Key Recommendations",
        "- Inspect the high-error subgroups identified above for systematic acquisition artifacts, label ambiguity, or cohort shift.",
        "- Do not retrain models solely by upsampling small bins without verifying raw sensor and clinical ground-truth quality.",
        "",
        "---",
        "*Generated by Model Forensics Workbench.*"
    ])

    content = "\n".join(lines)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)
    return output_path
